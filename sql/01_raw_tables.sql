CREATE DATABASE IF NOT EXISTS SKYPOINTS;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.RAW;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.STAGING;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.CORE;

USE SCHEMA SKYPOINTS.RAW;

CREATE TABLE IF NOT EXISTS MEMBER_PROFILE_RAW (
    RAW_LINE            VARCHAR,
    SOURCE_FILE_NAME    VARCHAR,
    SOURCE_LINE_NUMBER  NUMBER,
    LOADED_AT           TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS REDEMPTION_FEED_RAW (
    PAYLOAD VARIANT,
    SOURCE_FILE_NAME VARCHAR,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP
)