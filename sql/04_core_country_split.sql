USE SCHEMA SKYPOINTS.CORE;

-- Single Source of Truth: one row per member, the latest valid record.
CREATE OR REPLACE TABLE MEMBER_CURRENT AS
SELECT
    MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME,
    STATE, COUNTRY, DOB, IS_ACTIVE, AGE, STALE_MEMBER,
    SOURCE_FILE_NAME, SOURCE_LINE_NUMBER, FILE_BUSINESS_DATE
FROM SKYPOINTS.STAGING.MEMBER_PROFILE_STG
WHERE DQ_STATUS = 'VALID'
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY MEMBER_ID
    ORDER BY FILE_BUSINESS_DATE DESC, SOURCE_LINE_NUMBER DESC
) = 1;

-- One table per country, generated from the reference list instead of written by hand.
EXECUTE IMMEDIATE $$
DECLARE
    countries CURSOR FOR SELECT DISTINCT ISO_ALPHA3 FROM SKYPOINTS.STAGING.COUNTRY_CODE_MAP;
    stmt VARCHAR;
BEGIN
    FOR c IN countries DO
        stmt := 'CREATE OR REPLACE TABLE SKYPOINTS.CORE.MEMBERS_' || c.ISO_ALPHA3 ||
                ' AS SELECT * FROM SKYPOINTS.CORE.MEMBER_CURRENT WHERE COUNTRY = ''' || c.ISO_ALPHA3 || '''';
        EXECUTE IMMEDIATE :stmt;
    END FOR;
    RETURN 'Country tables rebuilt';
END;
$$;