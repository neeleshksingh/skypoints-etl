USE SCHEMA SKYPOINTS.RAW;

CREATE STAGE IF NOT EXISTS SKYPOINTS_LANDING;

-- FIELD_DELIMITER = NONE keeps each line whole; splitting happens in staging.
CREATE FILE FORMAT IF NOT EXISTS MEMBER_LINE_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = NONE;

CREATE FILE FORMAT IF NOT EXISTS REDEMPTION_JSON_FORMAT
    TYPE = JSON
    STRIP_OUTER_ARRAY = TRUE;

COPY INTO MEMBER_PROFILE_RAW (RAW_LINE, SOURCE_FILE_NAME, SOURCE_LINE_NUMBER)
FROM (
    SELECT $1, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER
    FROM @SKYPOINTS_LANDING
)
FILE_FORMAT = (FORMAT_NAME = MEMBER_LINE_FORMAT)
PATTERN = '.*MEMBERS_[0-9]{8}[.]txt';

COPY INTO REDEMPTION_FEED_RAW (PAYLOAD, SOURCE_FILE_NAME)
FROM (
    SELECT $1, METADATA$FILENAME
    FROM @SKYPOINTS_LANDING
)
FILE_FORMAT = (FORMAT_NAME = REDEMPTION_JSON_FORMAT)
PATTERN = '.*REDEMPTIONS_[0-9]{8}[.]json';